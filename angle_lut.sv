module angle_lut(
    input  logic [4:0] iter_idx,
    input  logic [1:0] coord_syst, // 2'b00: Linear, 2'b01: Circular, 2'b11: Hyperbolic, default: Linear
    output logic [31:0] result
  );

  logic [31:0] tan_inv_2i;
  logic [31:0] linear_2i;
  logic [31:0] tanh_inv_2i;

  logic [31:0] tan_inv_2i_temp;
  logic [31:0] linear_2i_temp;
  logic [31:0] tanh_inv_2i_temp;

  // ---------------------------------------------------------------------------
  // 1. Circular Coordinate System: arctan(2^(-i)) in radians
  // ---------------------------------------------------------------------------
  always_comb begin
    case (iter_idx)
      6'b0      : tan_inv_2i = 32'b00110010010000111111011010101001; // arctan(2^-0)
      6'b1      : tan_inv_2i = 32'b00011101101011000110011100000101; // arctan(2^-1)
      6'b10     : tan_inv_2i = 32'b00001111101011011011101011111101; // arctan(2^-2)
      6'b11     : tan_inv_2i = 32'b00000111111101010110111010100111; // arctan(2^-3)
      6'b100    : tan_inv_2i = 32'b00000011111111101010101101110111; // arctan(2^-4)
      6'b101    : tan_inv_2i = 32'b00000001111111111101010101011100; // arctan(2^-5)
      6'b110    : tan_inv_2i = 32'b00000000111111111111101010101011; // arctan(2^-6)
      6'b111    : tan_inv_2i = 32'b00000000011111111111111101010101; // arctan(2^-7)
      6'b1000   : tan_inv_2i = 32'b00000000001111111111111111101011; // arctan(2^-8)
      6'b1001   : tan_inv_2i = 32'b00000000000111111111111111111101; // arctan(2^-9)
      6'b1010   : tan_inv_2i = 32'b00000000000100000000000000000000; // arctan(2^-10)
      6'b1011   : tan_inv_2i = 32'b00000000000010000000000000000000; // arctan(2^-11)
      6'b1100   : tan_inv_2i = 32'b00000000000001000000000000000000; // arctan(2^-12)
      6'b1101   : tan_inv_2i = 32'b00000000000000100000000000000000; // arctan(2^-13)
      6'b1110   : tan_inv_2i = 32'b00000000000000010000000000000000; // arctan(2^-14)
      6'b1111   : tan_inv_2i = 32'b00000000000000001000000000000000; // arctan(2^-15)
      6'b10000  : tan_inv_2i = 32'b00000000000000000100000000000000; // arctan(2^-16)
      6'b10001  : tan_inv_2i = 32'b00000000000000000010000000000000; // arctan(2^-17)
      6'b10010  : tan_inv_2i = 32'b00000000000000000001000000000000; // arctan(2^-18)
      6'b10011  : tan_inv_2i = 32'b00000000000000000000100000000000; // arctan(2^-19)
      6'b10100  : tan_inv_2i = 32'b00000000000000000000010000000000; // arctan(2^-20)
      6'b10101  : tan_inv_2i = 32'b00000000000000000000001000000000; // arctan(2^-21)
      6'b10110  : tan_inv_2i = 32'b00000000000000000000000100000000; // arctan(2^-22)
      6'b10111  : tan_inv_2i = 32'b00000000000000000000000010000000; // arctan(2^-23)
      6'b11000  : tan_inv_2i = 32'b00000000000000000000000001000000; // arctan(2^-24)
      6'b11001  : tan_inv_2i = 32'b00000000000000000000000000100000; // arctan(2^-25)
      6'b11010  : tan_inv_2i = 32'b00000000000000000000000000010000; // arctan(2^-26)
      6'b11011  : tan_inv_2i = 32'b00000000000000000000000000001000; // arctan(2^-27)
      6'b11100  : tan_inv_2i = 32'b00000000000000000000000000000100; // arctan(2^-28)
      6'b11101  : tan_inv_2i = 32'b00000000000000000000000000000010; // arctan(2^-29)
      6'b11110  : tan_inv_2i = 32'b00000000000000000000000000000001; // arctan(2^-30)
      6'b11111  : tan_inv_2i = 32'b00000000000000000000000000000000; // arctan(2^-31)
      default   : tan_inv_2i = 32'b0;
    endcase
  end

  // ---------------------------------------------------------------------------
  // 2. Linear Coordinate System: 2^-i
  // ---------------------------------------------------------------------------
  always_comb begin
    case (iter_idx)
      6'b0      : linear_2i = 32'b01000000000000000000000000000000; // 2^-0
      6'b1      : linear_2i = 32'b00100000000000000000000000000000; // 2^-1
      6'b10     : linear_2i = 32'b00010000000000000000000000000000; // 2^-2
      6'b11     : linear_2i = 32'b00001000000000000000000000000000; // 2^-3
      6'b100    : linear_2i = 32'b00000100000000000000000000000000; // 2^-4
      6'b101    : linear_2i = 32'b00000010000000000000000000000000; // 2^-5
      6'b110    : linear_2i = 32'b00000001000000000000000000000000; // 2^-6
      6'b111    : linear_2i = 32'b00000000100000000000000000000000; // 2^-7
      6'b1000   : linear_2i = 32'b00000000010000000000000000000000; // 2^-8
      6'b1001   : linear_2i = 32'b00000000001000000000000000000000; // 2^-9
      6'b1010   : linear_2i = 32'b00000000000100000000000000000000; // 2^-10
      6'b1011   : linear_2i = 32'b00000000000010000000000000000000; // 2^-11
      6'b1100   : linear_2i = 32'b00000000000001000000000000000000; // 2^-12
      6'b1101   : linear_2i = 32'b00000000000000100000000000000000; // 2^-13
      6'b1110   : linear_2i = 32'b00000000000000010000000000000000; // 2^-14
      6'b1111   : linear_2i = 32'b00000000000000001000000000000000; // 2^-15
      6'b10000  : linear_2i = 32'b00000000000000000100000000000000; // 2^-16
      6'b10001  : linear_2i = 32'b00000000000000000010000000000000; // 2^-17
      6'b10010  : linear_2i = 32'b00000000000000000001000000000000; // 2^-18
      6'b10011  : linear_2i = 32'b00000000000000000000100000000000; // 2^-19
      6'b10100  : linear_2i = 32'b00000000000000000000010000000000; // 2^-20
      6'b10101  : linear_2i = 32'b00000000000000000000001000000000; // 2^-21
      6'b10110  : linear_2i = 32'b00000000000000000000000100000000; // 2^-22
      6'b10111  : linear_2i = 32'b00000000000000000000000010000000; // 2^-23
      6'b11000  : linear_2i = 32'b00000000000000000000000001000000; // 2^-24
      6'b11001  : linear_2i = 32'b00000000000000000000000000100000; // 2^-25
      6'b11010  : linear_2i = 32'b00000000000000000000000000010000; // 2^-26
      6'b11011  : linear_2i = 32'b00000000000000000000000000001000; // 2^-27
      6'b11100  : linear_2i = 32'b00000000000000000000000000000100; // 2^-28
      6'b11101  : linear_2i = 32'b00000000000000000000000000000010; // 2^-29
      6'b11110  : linear_2i = 32'b00000000000000000000000000000001; // 2^-30
      6'b11111  : linear_2i = 32'b00000000000000000000000000000000; // 2^-31
      default   : linear_2i = 32'b0;
    endcase
  end

  // ---------------------------------------------------------------------------
  // 3. Hyperbolic Coordinate System: atanh(2^-i) in radians
  // ---------------------------------------------------------------------------
  always_comb begin
    case (iter_idx)
      6'b0      : tanh_inv_2i = 32'b0;                                // atanh(2^-0) unused
      6'b1      : tanh_inv_2i = 32'b00100011001001111101010011110101; // atanh(2^-1)
      6'b10     : tanh_inv_2i = 32'b00010000010110001010111011111011; // atanh(2^-2)
      6'b11     : tanh_inv_2i = 32'b00001000000010101100010010001110; // atanh(2^-3)
      6'b100    : tanh_inv_2i = 32'b00000100000000010101011000100011; // atanh(2^-4)
      6'b101    : tanh_inv_2i = 32'b00000010000000000010101010110001; // atanh(2^-5)
      6'b110    : tanh_inv_2i = 32'b00000001000000000000010101010110; // atanh(2^-6)
      6'b111    : tanh_inv_2i = 32'b00000000100000000000000010101011; // atanh(2^-7)
      6'b1000   : tanh_inv_2i = 32'b00000000010000000000000000010101; // atanh(2^-8)
      6'b1001   : tanh_inv_2i = 32'b00000000001000000000000000000011; // atanh(2^-9)
      6'b1010   : tanh_inv_2i = 32'b00000000000100000000000000000000; // atanh(2^-10)
      6'b1011   : tanh_inv_2i = 32'b00000000000010000000000000000000; // atanh(2^-11)
      6'b1100   : tanh_inv_2i = 32'b00000000000001000000000000000000; // atanh(2^-12)
      6'b1101   : tanh_inv_2i = 32'b00000000000000100000000000000000; // atanh(2^-13)
      6'b1110   : tanh_inv_2i = 32'b00000000000000010000000000000000; // atanh(2^-14)
      6'b1111   : tanh_inv_2i = 32'b00000000000000001000000000000000; // atanh(2^-15)
      6'b10000  : tanh_inv_2i = 32'b00000000000000000100000000000000; // atanh(2^-16)
      6'b10001  : tanh_inv_2i = 32'b00000000000000000010000000000000; // atanh(2^-17)
      6'b10010  : tanh_inv_2i = 32'b00000000000000000001000000000000; // atanh(2^-18)
      6'b10011  : tanh_inv_2i = 32'b00000000000000000000100000000000; // atanh(2^-19)
      6'b10100  : tanh_inv_2i = 32'b00000000000000000000010000000000; // atanh(2^-20)
      6'b10101  : tanh_inv_2i = 32'b00000000000000000000001000000000; // atanh(2^-21)
      6'b10110  : tanh_inv_2i = 32'b00000000000000000000000100000000; // atanh(2^-22)
      6'b10111  : tanh_inv_2i = 32'b00000000000000000000000010000000; // atanh(2^-23)
      6'b11000  : tanh_inv_2i = 32'b00000000000000000000000001000000; // atanh(2^-24)
      6'b11001  : tanh_inv_2i = 32'b00000000000000000000000000100000; // atanh(2^-25)
      6'b11010  : tanh_inv_2i = 32'b00000000000000000000000000010000; // atanh(2^-26)
      6'b11011  : tanh_inv_2i = 32'b00000000000000000000000000001000; // atanh(2^-27)
      6'b11100  : tanh_inv_2i = 32'b00000000000000000000000000000100; // atanh(2^-28)
      6'b11101  : tanh_inv_2i = 32'b00000000000000000000000000000010; // atanh(2^-29)
      6'b11110  : tanh_inv_2i = 32'b00000000000000000000000000000001; // atanh(2^-30)
      6'b11111  : tanh_inv_2i = 32'b00000000000000000000000000000000; // atanh(2^-31)
      default   : tanh_inv_2i = 32'b0;
    endcase
  end

  // ---------------------------------------------------------------------------
  // 4. Output Selection 
  // ---------------------------------------------------------------------------
  assign tan_inv_2i_temp  = tan_inv_2i [31 : 0];
  assign linear_2i_temp   = linear_2i  [31 : 0];
  assign tanh_inv_2i_temp = tanh_inv_2i[31 : 0];

  // ---------------------------------------------------------------------------
  // 5. Output Multiplexer
  // coord_syst[1:0]:
  //   2'b00: Linear
  //   2'b01: Circular
  //   2'b11: Hyperbolic
  //   2'b10: Linear
  // ---------------------------------------------------------------------------
  assign result = coord_syst[1] ? (coord_syst[0] ? tanh_inv_2i_temp : linear_2i_temp):
                                  (coord_syst[0] ? tan_inv_2i_temp  : linear_2i_temp);

endmodule
